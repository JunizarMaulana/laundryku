create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nama varchar(40) not null,
  username varchar(25) unique not null,
  role varchar(20) not null default 'pelanggan' check (role in ('admin', 'pegawai', 'pelanggan')),
  alamat text,
  no_handphone varchar(15),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.layanan (
  id_layanan bigint generated by default as identity primary key,
  nama_layanan varchar(40) not null,
  harga_per_kg numeric(10,2) not null check (harga_per_kg > 0),
  aktif boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.pesanan (
  id_pesanan bigint generated by default as identity primary key,
  id_user uuid not null references public.profiles(id) on delete restrict,
  id_layanan bigint not null references public.layanan(id_layanan) on delete restrict,
  tanggal_pesanan timestamptz not null default now(),
  berat numeric(5,2) not null check (berat > 0),
  total_harga numeric(10,2) not null check (total_harga >= 0),
  status_pesanan varchar(20) not null default 'Diterima' check (status_pesanan in ('Diterima','Dicuci','Disetrika','Siap Diambil','Selesai')),
  estimasi varchar(40) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pembayaran (
  id_pembayaran bigint generated by default as identity primary key,
  id_pesanan bigint not null references public.pesanan(id_pesanan) on delete cascade,
  tanggal_pembayaran timestamptz not null default now(),
  total_bayar numeric(10,2) not null check (total_bayar > 0),
  metode_pembayaran varchar(30) not null,
  bukti_pembayaran varchar(255) not null,
  status_pembayaran varchar(20) not null default 'Menunggu' check (status_pembayaran in ('Menunggu','Terverifikasi','Ditolak')),
  created_at timestamptz not null default now()
);

create table if not exists public.keluhan (
  id_keluhan bigint generated by default as identity primary key,
  id_user uuid not null references public.profiles(id) on delete cascade,
  id_pesanan bigint not null references public.pesanan(id_pesanan) on delete cascade,
  tanggal_keluhan timestamptz not null default now(),
  isi_keluhan text not null,
  jawaban_keluhan text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.current_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid();
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  base_username text;
begin
  base_username := coalesce(nullif(new.raw_user_meta_data->>'username', ''), split_part(new.email, '@', 1));
  insert into public.profiles (id, nama, username, role, alamat, no_handphone)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'nama', ''), split_part(new.email, '@', 1)),
    left(base_username, 17) || case when exists(select 1 from public.profiles where username = left(base_username, 25)) then '-' || left(new.id::text, 7) else '' end,
    'pelanggan',
    nullif(new.raw_user_meta_data->>'alamat', ''),
    nullif(new.raw_user_meta_data->>'no_handphone', '')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.role is distinct from new.role and public.current_role() <> 'admin' then
    raise exception 'Hanya admin yang boleh mengubah role';
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists protect_profile_role_trigger on public.profiles;
create trigger protect_profile_role_trigger
  before update on public.profiles
  for each row execute procedure public.protect_profile_role();

alter table public.profiles enable row level security;
alter table public.layanan enable row level security;
alter table public.pesanan enable row level security;
alter table public.pembayaran enable row level security;
alter table public.keluhan enable row level security;

drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select to authenticated
using (id = auth.uid() or public.current_role() in ('admin','pegawai'));
drop policy if exists profiles_update on public.profiles;
create policy profiles_update on public.profiles for update to authenticated
using (id = auth.uid() or public.current_role() = 'admin')
with check (id = auth.uid() or public.current_role() = 'admin');

drop policy if exists layanan_read on public.layanan;
create policy layanan_read on public.layanan for select to authenticated using (true);
drop policy if exists layanan_admin_all on public.layanan;
create policy layanan_admin_all on public.layanan for all to authenticated
using (public.current_role() = 'admin') with check (public.current_role() = 'admin');

drop policy if exists pesanan_read on public.pesanan;
create policy pesanan_read on public.pesanan for select to authenticated
using (id_user = auth.uid() or public.current_role() in ('admin','pegawai'));
drop policy if exists pesanan_create on public.pesanan;
create policy pesanan_create on public.pesanan for insert to authenticated
with check (id_user = auth.uid());
drop policy if exists pesanan_staff_update on public.pesanan;
create policy pesanan_staff_update on public.pesanan for update to authenticated
using (public.current_role() in ('admin','pegawai'))
with check (public.current_role() in ('admin','pegawai'));
drop policy if exists pesanan_admin_delete on public.pesanan;
create policy pesanan_admin_delete on public.pesanan for delete to authenticated
using (public.current_role() = 'admin');

drop policy if exists pembayaran_read on public.pembayaran;
create policy pembayaran_read on public.pembayaran for select to authenticated
using (
  public.current_role() in ('admin','pegawai') or
  exists(select 1 from public.pesanan p where p.id_pesanan = pembayaran.id_pesanan and p.id_user = auth.uid())
);
drop policy if exists pembayaran_create on public.pembayaran;
create policy pembayaran_create on public.pembayaran for insert to authenticated
with check (exists(select 1 from public.pesanan p where p.id_pesanan = pembayaran.id_pesanan and p.id_user = auth.uid()));
drop policy if exists pembayaran_admin_update on public.pembayaran;
create policy pembayaran_admin_update on public.pembayaran for update to authenticated
using (public.current_role() = 'admin') with check (public.current_role() = 'admin');

drop policy if exists keluhan_read on public.keluhan;
create policy keluhan_read on public.keluhan for select to authenticated
using (id_user = auth.uid() or public.current_role() in ('admin','pegawai'));
drop policy if exists keluhan_create on public.keluhan;
create policy keluhan_create on public.keluhan for insert to authenticated
with check (
  id_user = auth.uid() and
  exists(select 1 from public.pesanan p where p.id_pesanan = keluhan.id_pesanan and p.id_user = auth.uid())
);
drop policy if exists keluhan_admin_update on public.keluhan;
create policy keluhan_admin_update on public.keluhan for update to authenticated
using (public.current_role() = 'admin') with check (public.current_role() = 'admin');

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.profiles, public.layanan, public.pesanan, public.pembayaran, public.keluhan to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.current_role() to authenticated;

